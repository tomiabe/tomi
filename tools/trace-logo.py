#!/usr/bin/env python3
"""Trace assets/logo-dark.png into SVG subpaths for the /logo experiment.

The PNG is the source of truth for the mark. We read its alpha channel, trace
the outline and the counter (the triangular cut-out), simplify each contour and
emit them as two SVG paths in js/logo-mark.js. The page draws them with
fill-rule="evenodd", then resamples and deforms them in the browser.

Requires: pillow, numpy, scikit-image
Usage: python3 tools/trace-logo.py
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image
from skimage import measure

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "logo-dark.png"
OUTPUT = ROOT / "js" / "logo-mark.js"

PAD = 6
TOLERANCE = 0.5


def to_path(contour):
    simplified = measure.approximate_polygon(contour, tolerance=TOLERANCE)[:-1]
    xy = [(point[1] - PAD, point[0] - PAD) for point in simplified]

    def fmt(value):
        return f"{value:.1f}".rstrip("0").rstrip(".")

    parts = [f"M{fmt(xy[0][0])} {fmt(xy[0][1])}"]
    parts.extend(f"L{fmt(x)} {fmt(y)}" for x, y in xy[1:])
    parts.append("Z")
    return "".join(parts)


def main():
    image = Image.open(SOURCE).convert("RGBA")
    width, height = image.size
    alpha = np.array(image.getchannel("A"))
    contours = measure.find_contours(np.pad(alpha, PAD) > 127, 0.5, fully_connected="high")
    contours.sort(key=len, reverse=True)

    if len(contours) != 2:
        raise SystemExit(f"Expected an outline and a counter shape, found {len(contours)}")

    paths = [to_path(contour) for contour in contours]
    contents = (
        "/* Generated by tools/trace-logo.py from assets/logo-dark.png. Do not edit by hand. */\n"
        "window.TOMI_MARK = {\n"
        f'  viewBox: "0 0 {width} {height}",\n'
        f"  paths: {json.dumps(paths)},\n"
        "};\n"
    )
    OUTPUT.write_text(contents, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(paths)} subpaths)")


if __name__ == "__main__":
    main()
